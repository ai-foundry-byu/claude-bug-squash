"""bugsquash.review_panel — the adversarial review gate (Product / Safety / Architecture).

Before any auto-bug-squash fix is merged, it must pass a review by a *panel* of
independent governors, each loyal to a different axis, none loyal to the agent
that wrote the fix or to shipping fast. This is the oversight layer: a fix can
clear the structural diff gate (``gate.py``) and STILL be vetoed here if a
reviewer sees a real problem.

Where this sits in the pipeline:

    triage → fixer.run_fix → gate.evaluate  ──(AUTO_MERGE)──▶  PANEL (this) ──▶ merge

The structural gate answers "is this diff mechanically safe to auto-merge?" (size
caps, deny-list, tier, rate limit). The panel answers the judgement question the
gate can't: "is this fix actually *right* — does it solve the reported bug without
breaking a product invariant, a user-facing behaviour, or architectural
coherence?" Both must pass before a merge.

DESIGN INVARIANTS:
  * **Scoped tools, not bypass.** Each reviewer is a read-only ``claude -p``
    (Read/Grep/Glob + git/rg/ls/cat/sed) — it inspects ground truth, never writes.
    No ``--permission-mode bypassPermissions``.
  * **A single BLOCK vetoes the merge.** The panel is conjunctive: APPROVE only
    when ALL reviewers approve. One clearly-parsed ``VERDICT: BLOCK`` from any seat
    sends the fix to human-gate instead of merging.
  * **Fail-OPEN per reviewer, fail-SAFE on the merge.** A reviewer that times out
    / crashes / returns unparseable output resolves to APPROVE *for that seat* (a
    flaky reviewer must not wedge every fix) — but the panel records the failure,
    and the overall posture stays conservative because shadow-mode + rate-limit +
    the structural gate are still in force upstream. Only a real, parsed veto
    BLOCKS.
  * **Hallucinated-veto resistance.** Each reviewer's prompt demands it RE-READ the
    actual code and CITE a real file/line for any BLOCK — a veto with no citation
    is downgraded to a soft concern, not a hard block.

Per-seat "souls" (the loyalty axis + what a BLOCK defends) load from agent
definition files generated by ``bug-squash init`` — tailored to YOUR product so
the reviews are high-quality for your codebase. When no file is found for a seat,
a built-in generic soul is used.

The whole module is pure given an injected ``runner`` (a ``(seat, prompt) -> str``
callable), so tests never spawn a live ``claude`` or touch the network.
"""
from __future__ import annotations

import os
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Optional

# The default three seats. Each carries a distinct loyalty so the panel is
# genuinely adversarial (not three copies of the same reviewer).
SEAT_PRODUCT = "product"
SEAT_SAFETY = "safety"
SEAT_ARCHITECTURE = "architecture"
SEATS = (SEAT_PRODUCT, SEAT_SAFETY, SEAT_ARCHITECTURE)

DEFAULT_MODEL = os.getenv("BUG_PANEL_MODEL", "opus")
DEFAULT_TIMEOUT_S = int(os.getenv("BUG_PANEL_TIMEOUT_S", "240"))
DEFAULT_ALLOWED_TOOLS = os.getenv(
    "BUG_PANEL_ALLOWED_TOOLS",
    "Read,Grep,Glob,Bash(git:*),Bash(rg:*),Bash(ls:*),Bash(cat:*),Bash(sed:*)",
)

_VERDICT_RE = re.compile(r"VERDICT\s*:\s*(APPROVE[D]?|BLOCK[ED]?|PASS|REJECT)", re.IGNORECASE)
# A real citation = a path-ish token (a file with an extension, or a slash+dot) OR
# an explicit line ref. A BLOCK with NO citation is treated as a soft concern
# (hallucination resistance). Deliberately conservative.
_CITATION_RE = re.compile(
    r"[\w./-]+\.[A-Za-z0-9]{1,6}\b"
    r"|\bline\s+\d+\b"
    r"|[\w./-]+:\d+\b",
    re.IGNORECASE,
)

# Built-in generic souls, used when no per-repo agent file exists for the seat.
BUILTIN_SOULS = {
    SEAT_PRODUCT: (
        "You are the PRODUCT reviewer — loyal ONLY to the product and its users, "
        "never to the agent that wrote this fix or to closing the ticket fast. "
        "BLOCK if the fix would change a user-facing behaviour the maintainers "
        "would not want, mask the real bug instead of fixing its root cause, "
        "regress a working feature, or 'fix' the wrong problem. You care about "
        "OUTCOME, not code style."
    ),
    SEAT_SAFETY: (
        "You are the SAFETY reviewer — loyal ONLY to operational safety and the "
        "maintainers' trust. BLOCK if the fix touches anything that could send/post "
        "as the product, move money, leak a secret, weaken a safety rail, bypass an "
        "approval gate, or do something irreversible without explicit sign-off. You "
        "are the 'will-this-burn-us' check. A clean, contained fix is fine."
    ),
    SEAT_ARCHITECTURE: (
        "You are the ARCHITECTURE reviewer — loyal ONLY to the codebase's long-term "
        "coherence. BLOCK if the fix duplicates an existing capability, violates a "
        "convention used elsewhere, builds on an assumption the code contradicts, or "
        "introduces a competing/incoherent pattern. You are NOT a lint reviewer — "
        "only architectural coherence matters."
    ),
}

_GENERIC_SOUL = (
    "You are the {seat_upper} reviewer for this codebase. Review this fix strictly "
    "from your seat's concern. BLOCK only for a real problem on your axis; a clean, "
    "contained, correct fix should be APPROVED."
)


@dataclass
class SeatVerdict:
    """One reviewer's decision."""

    seat: str
    verdict: str               # "approve" | "block"
    reasons: str               # human-readable explanation
    cited: bool = False        # a BLOCK that cited a real file/line (else soft)
    failed_open: bool = False   # error/timeout/unparseable → defaulted to approve
    raw: str = ""

    @property
    def blocks(self) -> bool:
        # A BLOCK only counts as a hard veto if it cited a real file/line.
        return self.verdict == "block" and self.cited


@dataclass
class PanelVerdict:
    """The panel's combined decision. ``approved`` only when no seat hard-blocks."""

    seats: tuple[SeatVerdict, ...] = ()

    @property
    def blockers(self) -> tuple[SeatVerdict, ...]:
        return tuple(s for s in self.seats if s.blocks)

    @property
    def soft_concerns(self) -> tuple[SeatVerdict, ...]:
        return tuple(s for s in self.seats if s.verdict == "block" and not s.cited)

    @property
    def approved(self) -> bool:
        return not self.blockers

    @property
    def failed_open_seats(self) -> tuple[SeatVerdict, ...]:
        return tuple(s for s in self.seats if s.failed_open)

    def headline(self) -> str:
        marks = []
        for s in self.seats:
            if s.blocks:
                marks.append(f"{s.seat}=BLOCK")
            elif s.verdict == "block":
                marks.append(f"{s.seat}=block(soft)")
            elif s.failed_open:
                marks.append(f"{s.seat}=open?")
            else:
                marks.append(f"{s.seat}=ok")
        return ("APPROVED " if self.approved else "VETOED ") + " ".join(marks)

    def to_dict(self) -> dict:
        return {
            "approved": self.approved,
            "headline": self.headline(),
            "blockers": [s.seat for s in self.blockers],
            "soft_concerns": [s.seat for s in self.soft_concerns],
            "seats": [
                {
                    "seat": s.seat,
                    "verdict": s.verdict,
                    "cited": s.cited,
                    "failed_open": s.failed_open,
                    "reasons": s.reasons[:600],
                }
                for s in self.seats
            ],
        }


def load_soul(seat: str, agents_dir: Optional[Path]) -> str:
    """Load a seat's soul from ``{agents_dir}/reviewer-{seat}.md`` (the body after
    any YAML front-matter), falling back to the built-in generic soul.

    The generated agent files let ``init`` tailor each reviewer to the product.
    """
    if agents_dir:
        cand = Path(agents_dir) / f"reviewer-{seat}.md"
        if cand.is_file():
            try:
                text = cand.read_text()
                # strip a leading YAML front-matter block if present
                if text.startswith("---"):
                    parts = text.split("---", 2)
                    if len(parts) == 3:
                        text = parts[2]
                text = text.strip()
                if text:
                    return text
            except Exception:
                pass
    return BUILTIN_SOULS.get(seat, _GENERIC_SOUL.format(seat_upper=seat.upper()))


def build_prompt(seat: str, *, ticket: dict, diff: str, soul: str) -> str:
    """The per-seat review prompt. Demands a re-read + a cited verdict."""
    title = (ticket.get("title") or "").strip()
    body = (ticket.get("body") or "").strip()
    repo = ticket.get("target_repo") or ticket.get("repo") or "this repo"
    sev = ticket.get("severity") or "?"
    return (
        f"{soul}\n\n"
        f"An autonomous bug-squash fix is up for a MERGE review. It already passed "
        f"the structural diff gate (size caps, deny-list, risk tier). Your job is "
        f"the JUDGEMENT call the structural gate can't make.\n\n"
        f"=== THE BUG ===\n"
        f"repo: {repo}   severity: {sev}\n"
        f"title: {title}\n"
        f"report: {body[:1500]}\n\n"
        f"Your job (non-interactive — do NOT ask questions):\n"
        f"1. Read the diff below.\n"
        f"2. RE-READ the actual current code for anything you will rule on — use "
        f"Read/Grep/Glob/git. The diff shows what changed; the repo shows what's "
        f"TRUE. Do not veto a symbol/file you have not confirmed exists.\n"
        f"3. Decide from YOUR seat's loyalty only. End with EXACTLY one line:\n"
        f"   `VERDICT: APPROVE`  (let it merge), or\n"
        f"   `VERDICT: BLOCK`    (must be fixed before any merge)\n"
        f"   then 1-4 bullets. For a BLOCK you MUST cite a real file (and line if "
        f"you can) — an uncited BLOCK will be treated as a soft concern, not a "
        f"veto. Only BLOCK for a real problem on YOUR axis.\n\n"
        f"=== DIFF ===\n"
        f"{(diff or '')[:60000]}\n"
        f"=== END DIFF ==="
    )


def parse_seat(seat: str, output: str) -> SeatVerdict:
    """Parse one reviewer's output. Fail-OPEN on anything unclear."""
    text = (output or "").strip()
    if not text:
        return SeatVerdict(seat, "approve", "no output — failing open for this seat",
                           failed_open=True)
    matches = list(_VERDICT_RE.finditer(text))
    if not matches:
        return SeatVerdict(seat, "approve",
                           "no parseable VERDICT line — failing open for this seat",
                           failed_open=True, raw=text[-1200:])
    token = matches[-1].group(1).lower()  # last verdict wins
    tail = text[matches[-1].end():].strip()
    if token.startswith("block") or token == "reject":
        cited = bool(_CITATION_RE.search(tail))
        return SeatVerdict(seat, "block", tail or "blocked (no reason given)",
                           cited=cited, raw=text[-2000:])
    return SeatVerdict(seat, "approve", tail or "approved", raw=text[-1200:])


def _real_runner(seat: str, prompt: str, *, cwd: Optional[str], timeout: int,
                 model: str, allowed_tools: str) -> str:
    """Spawn one scoped, read-only ``claude -p`` reviewer. Separated for tests."""
    env = dict(os.environ)
    # An OAuth token masquerading as an API key breaks `claude` locally; strip
    # anything that isn't a real sk-ant-api key so a CI runner with a genuine key
    # still works.
    for var in ("ANTHROPIC_API_KEY", "ANTHROPIC_API_KEYS"):
        if not env.get(var, "").startswith("sk-ant-api"):
            env.pop(var, None)
    cmd = [
        "claude", "-p", prompt,
        "--model", model,
        "--allowedTools", allowed_tools,
        "--permission-mode", "default",
    ]
    cp = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                        cwd=cwd, env=env)
    return cp.stdout or ""


def _review_one(seat: str, *, ticket: dict, diff: str, cwd: Optional[str],
                timeout: int, model: str, agents_dir: Optional[Path],
                runner: Optional[Callable[[str, str], str]]) -> SeatVerdict:
    """Run a single seat. ALWAYS returns a SeatVerdict (never raises)."""
    soul = load_soul(seat, agents_dir)
    prompt = build_prompt(seat, ticket=ticket, diff=diff, soul=soul)
    try:
        if runner is None:
            out = _real_runner(seat, prompt, cwd=cwd, timeout=timeout, model=model,
                               allowed_tools=DEFAULT_ALLOWED_TOOLS)
        else:
            out = runner(seat, prompt)
    except subprocess.TimeoutExpired:
        return SeatVerdict(seat, "approve", f"timed out after {timeout}s — failing open",
                           failed_open=True)
    except Exception as e:  # noqa: BLE001 — a reviewer crash must never crash the panel
        return SeatVerdict(seat, "approve", f"reviewer spawn failed ({e}) — failing open",
                           failed_open=True)
    return parse_seat(seat, out)


def review(
    *,
    ticket: dict,
    diff: str,
    cwd: Optional[str] = None,
    timeout: int = DEFAULT_TIMEOUT_S,
    model: str = DEFAULT_MODEL,
    seats: tuple[str, ...] = SEATS,
    agents_dir: Optional[Path] = None,
    runner: Optional[Callable[[str, str], str]] = None,
    parallel: bool = True,
) -> PanelVerdict:
    """Run the adversarial panel on a fix. ALWAYS returns a PanelVerdict.

    ``runner`` is an injectable ``(seat, prompt) -> str`` for tests; defaults to a
    real scoped ``claude -p`` spawn per seat. ``agents_dir`` points at the
    generated per-seat agent files (souls). The seats run in parallel by default.
    """
    if parallel and runner is None:
        with ThreadPoolExecutor(max_workers=max(1, len(seats))) as ex:
            futs = {
                ex.submit(_review_one, s, ticket=ticket, diff=diff, cwd=cwd,
                          timeout=timeout, model=model, agents_dir=agents_dir,
                          runner=runner): s
                for s in seats
            }
            results = {futs[f]: f.result() for f in futs}
        ordered = tuple(results[s] for s in seats)
    else:
        ordered = tuple(
            _review_one(s, ticket=ticket, diff=diff, cwd=cwd, timeout=timeout,
                        model=model, agents_dir=agents_dir, runner=runner)
            for s in seats
        )
    return PanelVerdict(seats=ordered)
